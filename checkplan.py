SAFETY_V = 50                                           # выше — опасное напряжение


def esr_norm(C):
    """Допустимое ESR электролита на 100 кГц (Ом) по ёмкости, эмпирически ≈ 5·C[мкФ]^−0,53."""
    return 5 * max(C * 1e6, 0.1) ** -0.53


def coil_voltage(c):
    m = re.search(r"(\d+(?:[.,]\d+)?)\s*[VВ]", str(c.get("value", "")) + " " + str(c.get("note", "")))
    return float(m.group(1).replace(",", ".")) if m else None


class Planner:
    def __init__(self, circ, phys, cands, symptoms):
        self.c, self.phys, self.cands, self.sym = circ, phys, cands, list(symptoms)
        self.U = dict(phys.get("node_voltages", {}))
        for n, v in circ.volt.items():
            self.U.setdefault(n, v)
        self.steps = []

    def add(self, stage, refs, what, expect, why="", cell=""):
        if not cell and refs:
            cell = self.c.comps.get(refs[0], {}).get("cell", "")
        self.steps.append({"stage": stage, "refs": list(refs), "cell": cell, "what": what,
                           "expect": expect, "why": why})

    # ---------- где ----------

    def focus(self, n=8):
        """Где вероятная причина: детали с наибольшей суммарной вероятностью, с ролью и местом."""
        agg = {}
        for k in self.cands:
            a = agg.setdefault(k["ref"], {"ref": k["ref"], "value": k["value"], "cell": k["cell"], "p": 0,
                                          "modes": [], "roles": k["roles"], "why": []})
            a["p"] += k["p"]
            a["modes"].append(k["mode"])
            a["why"] += [w for w in k["why"] if w not in a["why"]]
        top = sorted(agg.values(), key=lambda a: -a["p"])[:n]
        cells = {}
        for a in top:
            if a["cell"]:
                cells[a["cell"]] = cells.get(a["cell"], 0) + a["p"]
        return top, sorted(cells.items(), key=lambda kv: -kv[1])

    # ---------- шаги ----------

    def safety(self):
        hv = [n for n, v in self.U.items() if abs(v) >= SAFETY_V]
        if not hv:
            return
        mains = [n for n in hv if self.c.meta.get(n, {}).get("port")]
        self.add("Безопасность", [], "Отключите питание и проверьте его отсутствие на вводе"
                 + (f" ({', '.join(mains[:4])})" if mains else ""),
                 "0 В между всеми проводами ввода и на землю",
                 f"в схеме есть цепи с напряжением до {max(abs(self.U[n]) for n in hv):.0f} В")
        for ref, cc in self.c.comps.items():
            if cc.get("type") != "C" or "bus_cap" not in self.c.roles[ref]:
                continue
            C, _ = dg.parse_value(cc.get("value"))
            v = self.c.span_v(ref) or 0
            nets = set(self.c.pins(ref).values())
            bleed = [r for r, x in self.c.comps.items() if x.get("type") == "R" and set(self.c.pins(r).values()) == nets]
            if C and bleed:
                R, _ = dg.parse_value(self.c.comps[bleed[0]].get("value"))
                t5 = 5 * R * C if R else None
                how = f"сам разрядится через {bleed[0]} за 5τ = 5·R·C ≈ {t5:.0f} с" if t5 else "разрядите резистором"
            else:
                how = "разрядите резистором 1–5 кОм 5–10 Вт (не отвёрткой)"
            self.add("Безопасность", [ref], f"Разрядите {ref} {cc.get('value', '')}: {how}",
                     "на выводах < 36 В по мультиметру", f"конденсатор силовой шины, ~{v:.0f} В"
                     + (f", энергия W = C·U²/2 ≈ {C * v * v / 2:.1f} Дж" if C and v else ""))

